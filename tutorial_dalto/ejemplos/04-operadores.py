# suma y resta
suma = 12 + 5
resta = 12 - 5

# multiplicación y división
multiplicacion = 12 * 5
division = 12 / 5

# potencia y módulo
potencia = 12 ** 2
modulo = 12 % 5

# división entera
division_entera = 12 // 5

# Imprimir resultados
print("Suma:", suma)
print("Resta:", resta)
print("Multiplicación:", multiplicacion)
print("División:", division)
print("Potencia:", potencia)
print("Módulo:", modulo)
print("División entera:", division_entera)
